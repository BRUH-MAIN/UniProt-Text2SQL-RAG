"""Generate the self-contained Kaggle Benchmarks task for the single-shot baseline.

The prompt template, schema and questions are read from the repository (so the exact
deployed prompt is evaluated) and inlined into the generated file. Nothing needs to be
uploaded as a Kaggle Dataset.

    python -m evaluation.kaggle.make_task [--limit N]  ->  evaluation/kaggle/task_baseline.py
"""
import argparse
import base64
import json
from pathlib import Path

from db.connection import get_schema
from baseline.sql_chain import PROMPT_TEMPLATE

HERE = Path(__file__).parent
ROOT = HERE.parent

TASK_SOURCE = '''# %%
# Single-shot text-to-SQL baseline: the deployed prompt (baseline/sql_chain.py PROMPT_TEMPLATE) +
# the full DDL, one call per question. Generated by evaluation/kaggle/make_task.py - do not
# edit by hand. Inference only; execution and scoring happen locally.
#
# Lessons carried over from the sibling kbench project: sequential calls (n_jobs=1) with a
# manual retry loop (the platform forces max_attempts=1 for nested evaluate()), an explicit
# reasoning level on every call, and reasoning="low" because higher levels reserve quota
# up-front and can trip the daily cap.
import base64
import json
import time
import traceback

import kaggle_benchmarks as kbench
import pandas as pd

PAYLOAD = json.loads(base64.b64decode("__PAYLOAD__").decode("utf-8"))
PROMPT_TEMPLATE = PAYLOAD["prompt_template"]
SCHEMA = PAYLOAD["schema"]
REASONING_LEVEL = "low"
MAX_MANUAL_RETRIES = 4
RETRY_BACKOFF_S = [5, 15, 30, 60]

df = pd.DataFrame(PAYLOAD["questions"])


# %%
@kbench.task(name="uniprot_sql_one", store_task=False)
def generate_one(llm, qid: str, question: str) -> dict:
    prompt = PROMPT_TEMPLATE.format(schema=SCHEMA, question=question)
    last_error = None
    for attempt in range(MAX_MANUAL_RETRIES):
        try:
            with kbench.chats.new(f"sql:{qid}:{attempt}") as chat:
                text = llm.prompt(prompt, reasoning=REASONING_LEVEL)
                usage = chat.usage
            break
        except Exception as e:  # noqa: BLE001 - retry any transient failure
            last_error = e
            if attempt < MAX_MANUAL_RETRIES - 1:
                time.sleep(RETRY_BACKOFF_S[attempt])
    else:
        raise RuntimeError(f"All {MAX_MANUAL_RETRIES} attempts failed for {qid}: {last_error}") from last_error
    return {
        "id": qid,
        "raw_output": text,
        "input_tokens": usage.input_tokens,
        "output_tokens": usage.output_tokens,
        "input_cost_nanodollars": usage.input_tokens_cost_nanodollars,
        "output_cost_nanodollars": usage.output_tokens_cost_nanodollars,
        "latency_ms": usage.total_backend_latency_ms,
    }


# %%
@kbench.task(name="__TASK_NAME__", description="Single-shot UniProt text-to-SQL baseline (inference only)")
def full_run(llm) -> dict:
    with kbench.client.enable_cache():
        runs = generate_one.evaluate(
            llm=[llm], evaluation_data=df, on_failure="continue",
            max_attempts=1, n_jobs=1, timeout=180, remove_run_files=True,
        )
    completed = runs.completed_runs.as_dataframe()
    errored = runs.errored_runs
    return {
        "total": len(df),
        "successful": len(completed),
        "errored": len(errored),
        "error_messages": [str(r.error_message)[:500] for r in errored],
        "predictions": completed["result"].tolist() if len(completed) > 0 else [],
    }


try:
    full_run.run(llm=kbench.llm)
except Exception:
    traceback.print_exc()
    raise
'''


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=None, help="only the first N questions (smoke test)")
    ap.add_argument("--task-name", default="uniprot-sql-baseline")
    ap.add_argument("--out", default=str(HERE / "task_baseline.py"))
    args = ap.parse_args()

    questions = [json.loads(line) for line in (ROOT / "questions.jsonl").read_text().splitlines()]
    if args.limit:
        questions = questions[: args.limit]
    payload = {
        "prompt_template": PROMPT_TEMPLATE,
        "schema": get_schema(),
        "questions": [{"qid": q["id"], "question": q["q"]} for q in questions],
    }
    b64 = base64.b64encode(json.dumps(payload, ensure_ascii=False).encode("utf-8")).decode("ascii")
    src = TASK_SOURCE.replace("__PAYLOAD__", b64).replace("__TASK_NAME__", args.task_name)
    Path(args.out).write_text(src)
    print(f"wrote {args.out}: {len(questions)} questions, {len(src)/1024:.0f} KB")


if __name__ == "__main__":
    main()
